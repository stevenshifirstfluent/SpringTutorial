package sg.edu.nus.thmeleaf.tutorial;

public class InputForm {

    private String textValue;

    private Integer numberValue;

    private String passwordValue;

    private String hiddenValue;

    private String radioValue;

    private String dynamicRadioValue;


    public String getTextValue() {
        return textValue;
    }


    public void setTextValue(
            String textValue) {

        this.textValue = textValue;
    }


    public Integer getNumberValue() {
        return numberValue;
    }


    public void setNumberValue(
            Integer numberValue) {

        this.numberValue = numberValue;
    }


    public String getPasswordValue() {
        return passwordValue;
    }


    public void setPasswordValue(
            String passwordValue) {

        this.passwordValue = passwordValue;
    }


    public String getHiddenValue() {
        return hiddenValue;
    }


    public void setHiddenValue(
            String hiddenValue) {

        this.hiddenValue = hiddenValue;
    }


    public String getRadioValue() {
        return radioValue;
    }


    public void setRadioValue(
            String radioValue) {

        this.radioValue = radioValue;
    }


    public String getDynamicRadioValue() {
        return dynamicRadioValue;
    }


    public void setDynamicRadioValue(
            String dynamicRadioValue) {

        this.dynamicRadioValue =
                dynamicRadioValue;
    }
}